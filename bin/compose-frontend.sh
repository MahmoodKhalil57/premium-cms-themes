#!/usr/bin/env bash
# Compose a site frontend: the shared template (frontend-template/) plus the
# frontend of every plugin the site uses (plugins/<id>/frontend/src/ in the
# plugins repo, overlaid onto src/). Generates src/plugins/index.ts (client
# entry), src/plugins/server.ts (build-time hooks) and src/plugins/template.json
# (template + plugin versions — what "theme update" compares).
#
#   bin/compose-frontend.sh <out-dir> [plugin,plugin,…|all] [theme-id]
#
# env: PLUGINS_SRC (default ../premium-cms-plugins), THEMES_SRC (default this repo)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:?out dir}"; WANT="${2:-}"; THEME="${3:-}"
PLUGINS_SRC="${PLUGINS_SRC:-$ROOT/../premium-cms-plugins}"
THEMES_SRC="${THEMES_SRC:-$ROOT}"
[ -d "$PLUGINS_SRC/plugins" ] || { echo "compose-frontend: plugins repo not found at $PLUGINS_SRC (set PLUGINS_SRC)"; exit 1; }
mkdir -p "$OUT"
rsync -a --delete --exclude 'node_modules' --exclude 'dist' --exclude '.astro' --exclude 'bun.lock' --exclude 'pnpm-lock.yaml' "$THEMES_SRC/frontend-template/" "$OUT/"
python3 - "$OUT" "$WANT" "$THEME" "$PLUGINS_SRC" "$THEMES_SRC" <<'PY'
import json, os, shutil, subprocess, sys, datetime
out, want, theme, psrc, tsrc = sys.argv[1:6]
def sha(repo):
    try: return subprocess.check_output(["git", "-C", repo, "rev-parse", "--short", "HEAD"], stderr=subprocess.DEVNULL).decode().strip()
    except Exception: return None
avail = {}
for d in sorted(os.listdir(os.path.join(psrc, "plugins"))):
    fj = os.path.join(psrc, "plugins", d, "frontend", "frontend.json")
    if os.path.exists(fj):
        meta = json.load(open(fj)); man = json.load(open(os.path.join(psrc, "plugins", d, "manifest.json")))
        avail[d] = {"meta": meta, "version": man["version"], "dir": os.path.join(psrc, "plugins", d, "frontend", "src")}
wanted = list(avail) if want in ("all", "*") else [x for x in want.split(",") if x]
for w in wanted:
    if w not in avail: print(f"compose-frontend: plugin {w} has no frontend (or is unknown) — skipped")
# dependency closure, dependencies first
order = []
def add(pid, chain=()):
    if pid in order or pid not in avail: return
    if pid in chain: raise SystemExit(f"compose-frontend: dependency cycle {' → '.join(chain + (pid,))}")
    for dep in avail[pid]["meta"].get("dependsOn", []): add(dep, chain + (pid,))
    order.append(pid)
for w in wanted: add(w)
missing = [dep for pid in order for dep in avail[pid]["meta"].get("dependsOn", []) if dep not in avail]
if missing: raise SystemExit(f"compose-frontend: missing plugin frontends: {missing}")
src = os.path.join(out, "src")
for pid in order:
    base = avail[pid]["dir"]
    for root, _dirs, files in os.walk(base):
        for f in files:
            rel = os.path.relpath(os.path.join(root, f), base)
            dst = os.path.join(src, rel)
            if os.path.exists(dst) and not rel.startswith(f"plugins/{pid}/"):
                raise SystemExit(f"compose-frontend: {pid} would overwrite core file src/{rel}")
            os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy2(os.path.join(root, f), dst)
servers = [pid for pid in order if os.path.exists(os.path.join(src, "plugins", pid, "server.ts"))]
ident = lambda pid: "".join(p.capitalize() for p in pid.split("-"))
open(os.path.join(src, "plugins", "index.ts"), "w").write("// Generated by bin/compose-frontend.sh — the client entry of every plugin frontend this site uses.\n" + ("".join(f'import "./{pid}/index";\n' for pid in order) or "export {};\n"))
server = open(os.path.join(tsrc, "frontend-template", "src", "plugins", "server.ts")).read()
imports = "".join(f'import * as {ident(pid)} from "./{pid}/server";\n' for pid in servers)
listing = ", ".join(f'{{ id: "{pid}", ...{ident(pid)} }}' for pid in servers)
server = server.replace("export const plugins: PluginServer[] = [];", f"export const plugins: PluginServer[] = [{listing}];")
server = server.replace('import type { LayoutData, SiteIdentity } from "../lib/layout";\n', 'import type { LayoutData, SiteIdentity } from "../lib/layout";\n' + imports)
open(os.path.join(src, "plugins", "server.ts"), "w").write(server)
tpl = json.load(open(os.path.join(tsrc, "frontend-template", "package.json")))["version"]
info = {"template": tpl, "theme": theme or None, "plugins": {pid: avail[pid]["version"] for pid in order}, "composedAt": datetime.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"), "source": {"themes": sha(tsrc), "plugins": sha(psrc)}}
json.dump(info, open(os.path.join(src, "plugins", "template.json"), "w"), indent=2); open(os.path.join(src, "plugins", "template.json"), "a").write("\n")
json.dump(info, open(os.path.join(out, "template.json"), "w"), indent=2); open(os.path.join(out, "template.json"), "a").write("\n")
print(f"composed template {tpl}" + (f" for {theme}" if theme else "") + ": " + (", ".join(f"{pid}@{avail[pid]['version']}" for pid in order) or "no plugins"))
PY
